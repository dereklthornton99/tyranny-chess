const SRC = path.join(ROOT, 'src', 'tyranny.html');
/*
 * The markers are JS BLOCK COMMENTS, not HTML comments, because they sit INSIDE
 * the page's single <script> block — it opens at src/tyranny.html:422 and closes
 * at :1665, and the markers are at 903-904, just after the GAME / UI banner.
 *
 * That placement dictates the payload shape: a bare assignment with NO tags.
 * Emitting a nested <script>...</script> here would make the inner </script>
 * terminate the OUTER block early and kill the whole page.
 */
