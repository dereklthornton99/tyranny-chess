if (require.main === module) {
  /* --inline already ran and exited near the top of this file, before the engine
     require, so there is deliberately no --inline branch here. */
  const opts = {
    games: parseInt(arg('--games', '2500'), 10),
    seed: parseInt(arg('--seed', '20260914'), 10),
    bias: parseFloat(arg('--bias', '0.5')),
    target: parseInt(arg('--target', '20'), 10),
    msBudget: parseInt(arg('--ms', '600000'), 10),
    /* The sweep runs until the RAREST family reaches --target, so the common
       ones overshoot hard: one 500-game run found 171 restraints while still
       waiting on 27 multisteps. Shipping all of them would make two thirds of
       the set a single family. --cap keeps the first N of each in discovery
       order, which is deterministic under a seed, and the yield block below
       records BOTH the true number found and the number kept -- capping the
       set never hides the measurement. */
    cap: parseInt(arg('--cap', '40'), 10)
  };
  const out = arg('--out', OUT_DEFAULT);
  /*
   * The survival family is NOT swept for. It is derived from the Lichess CC0
   * puzzle database by tools/lichess-seed.js and committed as a file, because
   * the positions have to come from real games: 1.9 million mate lines were
   * replayed to find 153 of them, which no playout from the opening is going to
   * stumble into. This stays the single writer of puzzles.json - it reads that
   * file rather than a second writer appending to the output.
   */
  const survivalPath = arg('--survival', path.join(ROOT, 'puzzles', 'survival-seed.json'));
  /* --now exists so "the same --seed reproduces a byte-identical puzzles.json"
     (M3-T1-AC6) is literally true and testable. Everything else in the output is
     a pure function of the seed; the wall-clock stamp was the one thing that was
     not, and without a way to pin it the criterion could never be checked. */
  const now = arg('--now', new Date().toISOString().replace(/\.\d+Z$/, 'Z'));
  /* The Lichess-seeded multistep puzzles, mined by tools/lichess-multistep.js.
     `--multistep none` skips them, which is how "the generator alone reproduces
     the sweep's puzzles" is checked without the seed in the way. */
  const multistepPath = arg('--multistep', path.join(ROOT, 'puzzles', 'multistep-seed.json'));

  /* A path the caller TYPED must exist. The two defaults may legitimately be
     absent -- a checkout from before the seed was built -- but an explicit
     argument that points nowhere used to be skipped in silence: exit 0 and a
     file missing every seeded puzzle, found only when a later test compared the
     committed data to the seed. (Found by deepcheck: a one-letter typo in
     --multistep produced exactly that.) */
  if (process.argv.indexOf('--survival') >= 0 && !fs.existsSync(survivalPath)) {
    throw new Error('--survival ' + survivalPath + ' does not exist');
  }
  if (process.argv.indexOf('--multistep') >= 0 && multistepPath !== 'none' && !fs.existsSync(multistepPath)) {
    throw new Error('--multistep ' + multistepPath + ' does not exist (pass "none" to skip it deliberately)');
  }

  const puzzles = [];
  const counts = {}, yield_ = {};

  /* Both seeds are read and DERIVED before the sweep, so a malformed or stale
     one fails in seconds rather than after a 200-second sweep is thrown away.
     (This comment used to say exactly that while the sweep ran first; the order
     now matches what it always claimed.) */
  let survival = [];
  if (fs.existsSync(survivalPath)) {
    const seed = JSON.parse(fs.readFileSync(survivalPath, 'utf8'));
    survival = (seed.puzzles || []).map(function (p, i) {
      const S = fen(p.fen);
      const ms = legal(S, true);
      /* RE-DERIVED, not copied. The seed file supplies a position and where it
         came from; everything a reader could check is recomputed here from the
         FEN, and the seed's own answer is used only to CONTRADICT this one if
         the two tools ever disagree. A stored depth would have been one more
         claim nobody verifies. */
      const r = trySurvival(S, 3, true);
      if (!r) throw new Error('survival seed ' + p.source.id +
        ': the position no longer satisfies the predicate — ' + p.fen);
      if (sqName(r.sole.from) + sqName(r.sole.to) + (r.sole.promo || '') !== p.solutionUci) {
        throw new Error('survival seed ' + p.source.id + ': seeder says ' + p.solutionUci +
          ', predicate says ' + sqName(r.sole.from) + sqName(r.sole.to));
      }
      const e = buildEntry('sur-' + String(i + 1).padStart(4, '0'), 'survival',
        S, [r.sole], ms, legal(S, false).length);
      /* CC0 asks for no attribution. The link is here because a position a
         reader can trace back to a real game is worth more than one that
         appeared from nowhere, and the Lichess rating is a difficulty prior no
         predicate in this repo can compute. */
      e.source = p.source;
      e.depth = r.depth;
      e.difficulty = r.depth === 3 ? 3 : (ms.length > 3 ? 3 : 2);
      /* The losing moves and what refutes each one, recomputed the same way. */
      /* Compared by square, NOT by object identity: trySurvival ran its own
         legal() call, so its move objects are different instances from the ones
         in `ms` and `m !== r.sole` is true even for the solution — which put the
         answer in its own decoy list until the validator caught it. */
      const soleKey = r.sole.from + ':' + r.sole.to + ':' + (r.sole.promo || '-');
      e.decoys = ms.filter(function (m) {
        return m.from + ':' + m.to + ':' + (m.promo || '-') !== soleKey;
      }).map(function (m) {
        const T = apply(S, m);
        const kill = legal(T, true).filter(function (x) {
          return legal(apply(T, x), true).length === 0 && inCheck(apply(T, x), apply(T, x).turn);
        })[0];
        return { uci: sqName(m.from) + sqName(m.to) + (m.promo || ''), san: san(S, m, true),
                 refutedBy: kill ? san(T, kill, true) : null };
      });
      return e;
    });
  }

  let multistepSeed = null, seeded = [];
  if (multistepPath !== 'none' && fs.existsSync(multistepPath)) {
    multistepSeed = JSON.parse(fs.readFileSync(multistepPath, 'utf8'));
    seeded = deriveMultistepSeeds(multistepSeed);
  }

  console.error('sweeping: games<=' + opts.games + ' seed=' + opts.seed + ' bias=' + opts.bias + ' target=' + opts.target + '/family');
  const r = sweep(opts);

  /* The one seed check that needs the sweep: a Lichess position must not also be
     a puzzle the playout found. Throws rather than dropping one, because a
     duplicate means the two sources overlap in a way nobody has looked at. */
  if (seeded.length) {
    const taken = new Set();
    FAMILIES.forEach(function (F) { r.found[F.name].forEach(function (p) { taken.add(p.fen); }); });
    seeded.forEach(function (p) {
      if (taken.has(p.fen)) throw new Error('multistep seed ' + p.source.id +
        ' is also found by the sweep -- ' + p.fen);
    });
  }

  FAMILIES.forEach(function (F) {
    const all = r.found[F.name];
    const got = all.slice(0, opts.cap);
    counts[F.name] = got.length;
    /* Measured yield, recorded either way (M3-T1-AC5). A family that comes up
       short says so here in a number; the predicate is never loosened to make
       the count look better. */
    yield_[F.name] = {
      found: all.length,
      kept: got.length,
      cap: opts.cap,
      target: opts.target,
      short: Math.max(0, opts.target - all.length),
      perThousandUnique: r.unique ? +(all.length / r.unique * 1000).toFixed(3) : 0
    };
    /* predicateSeconds deliberately does NOT go in the file. It is wall-clock,
       so writing it would break "the same --seed reproduces a byte-identical
       puzzles.json" (M3-T1-AC6) by two bytes and nothing else -- which is
       exactly how this was found. It is printed below instead. */
    got.forEach(function (p) { puzzles.push(p); });
    /* The Lichess-seeded puzzles are the same family and go straight after the
       sweep's, so the file stays grouped tactical, restraint, multistep,
       survival -- the order the page and tests/browser.js read it in. The
       family count includes them (the page and the validator count by family);
       the sweep's own yield above stays about the sweep, and the seed's is
       recorded beside it rather than blended in. */
    if (F.name === 'multistep' && seeded.length) {
      seeded.forEach(function (p) { puzzles.push(p); });
      counts.multistep = got.length + seeded.length;
      yield_.multistepSeeded = {
        kept: seeded.length,
        rowsScanned: multistepSeed.scan.rowsScanned,
        minReplies: multistepSeed.scan.minReplies,
        candidates: multistepSeed.selection.candidates
      };
    }
  });

  if (survival.length) {
    counts.survival = survival.length;
    yield_.survival = { found: survival.length, kept: survival.length, cap: survival.length,
      target: 0, short: 0, perThousandUnique: 0 };
    survival.forEach(function (p) { puzzles.push(p); });
  }

  const doc = {
    /* Schema 5 added `line` and a multistep `source`; schema 4 retired the
       escape family value and added survival with its source/depth fields. Each
       is bumped WITH the page reader in the same change -- and tests/puzzles.js
       reads SCHEMA from this file, so the generator and the committed data
       cannot silently disagree about which one they are. */
    schema: SCHEMA,
    generatedAt: now,
    generator: {
      strategy: 'check-biased playout from startState, depth-free predicates',
      familyPrecedence: FAMILIES.map(function (F) { return F.name; }).concat(survival.length ? ['survival'] : []),
      survivalSource: survival.length ? { file: path.basename(survivalPath), db: 'lichess-cc0' } : null,
      /* Only present when there is a seed, so a run without one produces the
         exact byte layout it always did. */
      ...(seeded.length ? { multistepSource: { file: path.basename(multistepPath), db: 'lichess-cc0' } } : {}),
      checkBias: opts.bias,
      games: r.games,
      positionsVisited: r.positions,
      uniquePositions: r.unique,
      seed: opts.seed,
      target: opts.target,
      yield: yield_,
      tool: 'tools/gen-puzzles.js'
    },
    counts: counts,
    puzzles: puzzles
  };
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, JSON.stringify(doc, null, 2) + '\n', 'utf8');

  console.error('games=' + r.games + ' positions=' + r.positions + ' unique=' + r.unique +
                ' in ' + (r.ms / 1000).toFixed(1) + 's');
  FAMILIES.forEach(function (F) {
    const y = yield_[F.name];
    console.error('  ' + F.name.padEnd(10) + y.kept + ' kept of ' + y.found + ' found, target ' + y.target +
      (y.short ? '  SHORT BY ' + y.short : '          ') +
      '  ' + y.perThousandUnique + '/1000 unique   ' +
      (r.predMs[F.name] / 1000).toFixed(1) + 's in the predicate');
  });
  console.error('wrote ' + out);
}

module.exports = { isMate, matesIn2, tryEscape, tryTactical, tryMultistep, tryRestraint, sweep, mulberry32,
                   SCHEMA, buildEntry, deriveMultistepSeeds };
